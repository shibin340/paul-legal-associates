// Editorial data stays in one source. Browsers receive catalogue metadata and
// only the article body requested by the current route.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { loadSource } = require('./load-source');
const root = path.resolve(__dirname, '..');
const sourcePath = path.join(root, 'src/data/index.ts');
const source = fs.readFileSync(sourcePath, 'utf8');
const marker = 'export const ARTICLES: Article[] = [';
if (source.split(marker).length !== 2) throw new Error('Editorial article marker changed.');
const prefix = source.slice(0, source.indexOf(marker)).replace(', Article }', ' }');
fs.writeFileSync(path.join(root, 'src/data/site.ts'), '// Generated by prepare-browser-data.js; edit data/index.ts.\n' + prefix);
const { ARTICLES } = loadSource(sourcePath);
const summaries = ARTICLES.map(({ content, ...summary }) => summary);
fs.writeFileSync(path.join(root, 'src/data/articleIndex.json'), JSON.stringify(summaries));
const directory = path.join(root, 'public/content/insights');
fs.rmSync(directory, { recursive: true, force: true });
fs.mkdirSync(directory, { recursive: true });
const paths = {};
for (const article of ARTICLES) {
  if (!/^[a-z0-9-]+$/.test(article.slug) || !Array.isArray(article.content)) throw new Error('Invalid article.');
  const json = JSON.stringify(article);
  const hash = crypto.createHash('sha256').update(json).digest('hex').slice(0, 12);
  const filename = `${article.slug}.${hash}.json`;
  fs.writeFileSync(path.join(directory, filename), json);
  paths[article.slug] = `/content/insights/${filename}`;
}
fs.writeFileSync(path.join(root, 'src/data/articleContentPaths.json'), JSON.stringify(paths));
console.log(`Prepared ${ARTICLES.length} article summaries and separate content files.`);
